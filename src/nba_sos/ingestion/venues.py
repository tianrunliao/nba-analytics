"""Venue reference data.

Two files under ``configs/``:

``venue_aliases.csv`` (hand-curated): one row per (arena_name, arena_city) string seen in
the schedule, mapped to a physical ``venue_id`` and its Wikidata item. ``neutral_site``
marks venues outside every NBA team's home market (international games, Las Vegas).

``venues.csv`` (generated by :func:`build_venue_table`): one row per ``venue_id`` with
Wikidata coordinates and an IANA timezone derived offline from those coordinates.
"""
from __future__ import annotations

from pathlib import Path

import pandas as pd
import requests

SPARQL_CANDIDATES = """
SELECT DISTINCT ?name ?item ?itemLabel ?itemDescription ?coord WHERE {
  VALUES ?name { %(values)s }
  { ?item rdfs:label ?name } UNION { ?item skos:altLabel ?name }
  ?item wdt:P625 ?coord .
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}"""

SPARQL_BY_QID = """
SELECT ?item ?itemLabel ?coord WHERE {
  VALUES ?item { %(values)s }
  ?item wdt:P625 ?coord .
  SERVICE wikibase:label { bd:serviceParam wikibase:language "en". }
}"""


def parse_wkt_point(wkt: str) -> tuple[float, float]:
    """'Point(lon lat)' -> (lat, lon)."""
    inner = wkt[wkt.index("(") + 1: wkt.index(")")]
    lon, lat = (float(v) for v in inner.split())
    return lat, lon


def _sparql(query: str, cfg: dict) -> list[dict]:
    r = requests.get(cfg["sparql_url"], params={"query": query, "format": "json"},
                     headers={"User-Agent": cfg["user_agent"]}, timeout=60)
    r.raise_for_status()
    return r.json()["results"]["bindings"]


def lookup_candidates(names: list[str], cfg: dict) -> pd.DataFrame:
    """Wikidata items whose English label/alias equals each arena name (for manual review).
    One batched query, to stay within the Wikidata Query Service rate limits."""
    values = " ".join('"{}"@en'.format(n.replace('"', '\\"')) for n in sorted(set(names)))
    rows = []
    for b in _sparql(SPARQL_CANDIDATES % {"values": values}, cfg):
        lat, lon = parse_wkt_point(b["coord"]["value"])
        rows.append({"arena_name": b["name"]["value"],
                     "qid": b["item"]["value"].rsplit("/", 1)[-1],
                     "label": b.get("itemLabel", {}).get("value"),
                     "description": b.get("itemDescription", {}).get("value"),
                     "latitude": lat, "longitude": lon})
    return pd.DataFrame(rows)


def fetch_coordinates(qids: list[str], cfg: dict) -> pd.DataFrame:
    values = " ".join(f"wd:{q}" for q in sorted(set(qids)))
    rows = []
    for b in _sparql(SPARQL_BY_QID % {"values": values}, cfg):
        lat, lon = parse_wkt_point(b["coord"]["value"])
        rows.append({"wikidata_qid": b["item"]["value"].rsplit("/", 1)[-1],
                     "wikidata_label": b["itemLabel"]["value"], "latitude": lat,
                     "longitude": lon})
    return pd.DataFrame(rows)


def timezone_for(lat: float, lon: float) -> str | None:
    from timezonefinder import TimezoneFinder
    return TimezoneFinder().timezone_at(lat=lat, lng=lon)


def build_venue_table(aliases: pd.DataFrame, coords: pd.DataFrame, retrieved_at: str) -> pd.DataFrame:
    """One row per venue_id. Fails if a venue maps to several QIDs or has no coordinates.
    Wikidata may hold several coordinate statements for one item; their mean is used and
    the spread is kept so it can be audited."""
    per_venue = aliases.groupby("venue_id").agg(
        wikidata_qid=("wikidata_qid", "unique"), neutral_site=("neutral_site", "max"))
    multi = per_venue[per_venue.wikidata_qid.map(len) != 1]
    if len(multi):
        raise ValueError(f"venues mapped to several Wikidata items: {multi.index.tolist()}")
    per_venue["wikidata_qid"] = per_venue.wikidata_qid.map(lambda a: a[0])
    c = coords.groupby("wikidata_qid").agg(
        wikidata_label=("wikidata_label", "first"), latitude=("latitude", "mean"),
        longitude=("longitude", "mean"), n_coords=("latitude", "size"),
        coord_spread_deg=("latitude", lambda s: float(s.max() - s.min()))).reset_index()
    out = per_venue.reset_index().merge(c, on="wikidata_qid", how="left")
    missing = out[out.latitude.isna()]
    if len(missing):
        raise ValueError(f"no Wikidata coordinates for: {missing.venue_id.tolist()}")
    out["timezone"] = [timezone_for(a, b) for a, b in zip(out.latitude, out.longitude)]
    out["coord_source"] = "wikidata P625"
    out["retrieved_at"] = retrieved_at
    return out.sort_values("venue_id").reset_index(drop=True)


def load_venue_config(configs_dir: Path) -> tuple[pd.DataFrame, pd.DataFrame]:
    aliases = pd.read_csv(configs_dir / "venue_aliases.csv", keep_default_na=False)
    aliases["neutral_site"] = aliases.neutral_site.astype(str).str.lower().eq("true")
    venues = pd.read_csv(configs_dir / "venues.csv")
    return aliases, venues
