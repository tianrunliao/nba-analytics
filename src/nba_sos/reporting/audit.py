"""Generate reports/data_audit.md from the build outputs."""

from __future__ import annotations

from datetime import UTC, datetime

import pandas as pd


def _md(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    if df is None or len(df) == 0:
        return "_(none)_\n"
    d = df.copy()
    for c in d.columns:
        if pd.api.types.is_float_dtype(d[c]):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else format(v, floatfmt))
    header = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in d.itertuples(index=False)]
    return "\n".join([header, sep, *rows]) + "\n"


def out_consistency(availability: pd.DataFrame, player_games: pd.DataFrame) -> pd.DataFrame:
    """Share of pre-game 'Out' players (matched to an id) who indeed logged no minutes.
    Audit only; uses post-game box scores, so never a feature."""
    a = availability[availability.player_id.notna()]
    played = player_games[player_games.minutes > 0][["game_id", "player_id"]].assign(played=True)
    m = a.merge(played, on=["game_id", "player_id"], how="left")
    m["played"] = m.played.astype("boolean").fillna(False).astype(bool)
    return m.groupby("injury_status").agg(n=("played", "size"), share_played=("played", "mean")).reset_index()


def write_audit(
    paths,
    cfg,
    *,
    store,
    games,
    all_games,
    schedule,
    checks,
    excluded,
    venues,
    aliases,
    counts,
    deviations,
    selection,
    parse_info,
    parsed,
    availability,
    team_status,
    player_games,
    features,
    sos,
    backtest,
    predictions,
) -> None:
    L: list[str] = []
    w = L.append
    w("# Data audit\n")
    w(f"Generated (UTC): {datetime.now(UTC).isoformat(timespec='seconds')}\n")
    w("Generated by `python -m nba_sos.pipeline build`; every number comes from the raw snapshots in `data/raw/`.\n")

    # 1 sources
    w("## 1. Sources and fetch times\n")
    man = pd.DataFrame(store.read_manifest())
    stats = man[man.source == "stats.nba.com"]
    if len(stats):
        w(
            _md(
                stats[["name", "season", "fetched_at", "bytes"]]
                .drop_duplicates(["name", "season"], keep="last")
                .sort_values(["name", "season"])
            )
        )
    w(
        "\nThe upstream endpoints give no per-record update times: `fetched_at` is when we fetched, so the "
        "revision history cannot be reconstructed. Historical schedules are the final schedules as played "
        "(postponed dates, NBA Cup knockout pairings), not the versions published at the start of each season.\n"
    )

    # 2 coverage
    w("## 2. Coverage\n")
    cov = (
        all_games.groupby("season")
        .agg(
            games=("game_id", "size"),
            first=("game_date", "min"),
            last=("game_date", "max"),
            neutral=("is_neutral", "sum"),
            source_neutral=("source_is_neutral", "sum"),
        )
        .reset_index()
    )
    cov["teams"] = [
        pd.concat(
            [all_games[all_games.season == s].home_team_id, all_games[all_games.season == s].away_team_id]
        ).nunique()
        for s in cov.season
    ]
    w(_md(cov))
    seasons = cfg["data_sources"]["seasons"]
    w(
        f"\n{', '.join(seasons['prior'])}: used only for the pre-season ratings of the first historical season "
        f"({seasons['historical'][0]}).\n"
    )
    w(
        "\nNon-regular-season games excluded from the schedule (by game_id prefix: 001 preseason, "
        "002 regular season, 003 All-Star, 004 playoffs, 005 play-in, 006 NBA Cup final):\n"
    )
    ex = pd.DataFrame([{"season": s, **{f"prefix_{k}": v for k, v in d.items()}} for s, d in excluded.items()])
    w(_md(ex.fillna(0).astype({c: int for c in ex.columns if c != "season"})))

    # 3 validation
    w("## 3. Validation\n")
    bad = checks[~checks.passed]
    w(
        f"{len(checks)} checks, {len(bad)} not passed "
        f"({int((bad.severity == 'error').sum())} errors, {int((bad.severity == 'warning').sum())} warnings). "
        "Full results in `reports/validation_results.csv`.\n"
    )
    w("\nChecks not passed or worth attention:\n")
    attention = checks[
        ~checks.passed | checks.check.isin(["possession_source_agreement", "neutral_flag_source_vs_venue"])
    ]
    w(_md(attention[["check", "season", "severity", "passed", "detail"]]))

    # 4 neutral & venues
    w("## 4. Neutral sites and venues\n")
    nn = games[games.is_neutral][
        [
            "season",
            "game_id",
            "game_date",
            "home_team",
            "away_team",
            "arena_name",
            "arena_city",
            "source_is_neutral",
            "game_label",
            "game_sublabel",
        ]
    ]
    w(
        "`is_neutral` = the source's `isNeutral` flag or a venue marked as a neutral site (international "
        "games, NBA Cup in Las Vegas). The source does not flag these games before 2024-25.\n"
    )
    w(_md(nn))
    w(
        f"\nVenues: {aliases.shape[0]} name/city combinations map to {venues.shape[0]} physical venues "
        "(`configs/venue_aliases.csv`, curated by hand; coordinates from Wikidata P625, time zones derived "
        "offline from the coordinates).\n"
    )
    w(_md(venues[["venue_id", "wikidata_qid", "latitude", "longitude", "timezone", "neutral_site"]]))

    # 5 matchups
    w("## 5. Matchup counts\n")
    rs = counts.groupby(["season", "team"]).n_games.sum()
    w(
        f"Games per team: min {rs.min()}, max {rs.max()}. Team-relation combinations that differ from the "
        f"traditional 4/4/3/2 structure: {len(deviations)}.\n"
    )
    if len(deviations):
        w(
            _md(
                deviations.groupby(["season", "relation", "actual", "traditional"])
                .size()
                .rename("n_teams")
                .reset_index()
            )
        )

    # 6 injuries
    w("## 6. Injury reports\n")
    sel = selection.merge(games[["game_id", "season"]], on="game_id")
    cov_i = (
        sel.groupby("season")
        .agg(games=("game_id", "size"), with_report=("report_path", lambda s: s.notna().sum()))
        .reset_index()
    )
    ts = (
        team_status.groupby("season")
        .agg(
            team_games=("game_id", "size"),
            usable=("snapshot_usable", "sum"),
            not_submitted=("not_submitted", "sum"),
            game_not_in_report=("game_in_report", lambda s: int((~s).sum())),
        )
        .reset_index()
    )
    cov_i = cov_i.merge(ts, on="season", how="outer")
    cov_i["usable_share"] = cov_i.usable / cov_i.team_games
    w(_md(cov_i))
    if len(sel.dropna(subset=["report_path"])):
        lead = games.set_index("game_id").tipoff_utc - sel.set_index("game_id").report_published_at_utc
        lead_min = lead.dropna().dt.total_seconds() / 60
        w(
            f"\nMinutes from the selected report's publication to tip-off: median {lead_min.median():.0f}, "
            f"min {lead_min.min():.0f}, max {lead_min.max():.0f}. Every selected report precedes tip-off.\n"
        )
    if parse_info is not None and len(parse_info):
        perr = parse_info.parse_error.notna().sum()
        w(
            f"\nReport files parsed: {len(parse_info)}; failed: {perr}; wrapped-line fragments that could not "
            f"be reattached: {int(parse_info.orphan_fragments.fillna(0).sum())}.\n"
        )
        if perr:
            w(_md(parse_info[parse_info.parse_error.notna()][["report_path", "parse_error"]].head(20)))
    if len(availability):
        mr = (
            availability.match_method.fillna("unmatched")
            .value_counts()
            .rename_axis("match_method")
            .rename("n")
            .reset_index()
        )
        mr["share"] = mr.n / mr.n.sum()
        w("\nPlayer names matched to nba_api player IDs:\n")
        w(_md(mr))
        w(
            "\nUnmatched players are mostly players who did not appear all season (two-way contracts, long-term "
            "injuries), whose prior minutes are zero anyway. Matching uses the season's full player list; it "
            "only identifies players and enters no feature value.\n"
        )
        inv = availability[~availability.status_valid.astype(bool)]
        w(f"\nRows with a status outside {{Out, Doubtful, Questionable, Probable, Available}}: {len(inv)}.\n")
        oc = out_consistency(availability, player_games)
        w(
            "\nConsistency audit (post-game check, never a feature): share of players with each pre-game status who played:\n"
        )
        w(_md(oc))

    # 7 features
    w("## 7. Pre-game features\n")
    num = features.select_dtypes("number").columns.tolist() + ["is_back_to_back"]
    nul = features[num].isna().mean().rename("null_share").reset_index().rename(columns={"index": "feature"})
    w(_md(nul))
    w(
        "\nResult-based features use only games on ET dates strictly before the game day; each season's "
        "first-game cumulative values and rest days are empty, not filled. Injury features are empty when no "
        "usable pre-game snapshot exists, not filled with 0. `as_of_timestamp` = max(tip-off of the latest game "
        "on an earlier date + 4 hours, publication time of the injury report used); the build checks that it "
        "precedes tip-off.\n"
    )
    desc = (
        features[
            [
                "rest_days",
                "games_last_4_days",
                "games_last_7_days",
                "travel_distance_km",
                "timezone_change_hours",
                "consecutive_road_games",
                "missing_minutes_prior_avg",
            ]
        ]
        .describe()
        .T
    )
    w(_md(desc.reset_index().rename(columns={"index": "feature"}), ".2f"))

    # 8 sos
    w("## 8. Static SOS\n")
    w(
        "`retro_*` uses opponents' final season records (descriptive only); `causal_*` uses opponents' "
        "records before each game (the version usable for forecasting). Rank 1 = hardest schedule. Top 5 per "
        "season by retro_owp:\n"
    )
    top = sos.sort_values(["season", "retro_owp_rank"]).groupby("season").head(5)
    w(
        _md(
            top[
                [
                    "season",
                    "team",
                    "win_pct",
                    "retro_owp",
                    "retro_owp_rank",
                    "causal_owp_mean",
                    "causal_owp_mean_rank",
                    "retro_opp_net_rating",
                    "causal_opp_net_rating_mean",
                ]
            ]
        )
    )
    corr = sos.groupby("season").apply(
        lambda d: d.retro_owp.corr(d.causal_owp_mean, method="spearman"), include_groups=False
    )
    w("\nSpearman correlation of retro and causal OWP: " + ", ".join(f"{s} {v:.2f}" for s, v in corr.items()) + "\n")

    # 9 baseline
    w("## 9. Baseline: pre-season rating + home court\n")
    w(
        "Expanding-window rolling backtest: each test season is trained on earlier seasons only. `b` is the "
        "coefficient from last season's net-rating difference to this season's margin, `hca` the home-court "
        "advantage (points), `sigma` the training residual sd.\n"
    )
    cols = [
        "test_season",
        "train_seasons",
        "b",
        "hca",
        "sigma",
        "n_games",
        "preseason_log_loss",
        "constant_log_loss",
        "preseason_brier",
        "constant_brier",
        "preseason_margin_mae",
        "constant_margin_mae",
        "preseason_margin_rmse",
        "constant_margin_rmse",
        "preseason_ece",
    ]
    w(_md(backtest[[c for c in cols if c in backtest.columns]]))
    from ..evaluation.metrics import calibration_table

    cal = calibration_table(predictions.home_win.to_numpy(float), predictions.pred_p_home.to_numpy(float))
    w("\nCalibration of the pooled test set:\n")
    w(_md(cal))

    (paths.reports / "data_audit.md").write_text("\n".join(L), encoding="utf-8")
